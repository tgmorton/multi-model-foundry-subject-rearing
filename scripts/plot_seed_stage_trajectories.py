#!/usr/bin/env python3
"""Plot seed-resolved early starts and late continuations.

The input is the tidy aggregate generated by ``plot_foundry_trajectories.py``.
Each thin line is one seed after equal-weight averaging across intervention
conditions and item categories.  The heavy line is the mean across seeds and
the ribbon is +/- one standard error across those seed-level means.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


REPO = Path(__file__).resolve().parents[1]
FIG_DIR = REPO / "analysis/eval_v2/figures/foundry_trajectories"
INPUT = FIG_DIR / "early_vs_continuation_aggregates.csv"
ARCHES = ["gpt2_small", "gpt2_medium", "gpt2_large", "bert_large", "lstm", "mamba_370m"]
STAGES = {
    "early": ("early-only", "Early-only starts"),
    "late": ("late continuation", "Late continuations"),
}


def _bin_seed_trajectories(d: pd.DataFrame, n_bins: int = 32) -> pd.DataFrame:
    """Average rows within seed and log-spaced token bins."""
    if d.empty:
        return d
    # First collapse all categories/conditions to a seed-level trajectory at
    # each token coordinate.  This is the independent unit for uncertainty.
    seed_tok = (
        d.groupby(["architecture", "seed", "tokens_seen"], as_index=False)["preference"]
        .mean()
        .sort_values(["architecture", "seed", "tokens_seen"])
    )
    out = []
    for arch, q in seed_tok.groupby("architecture", sort=False):
        q = q.copy()
        positive = q.loc[q.tokens_seen > 0, "tokens_seen"]
        if positive.empty:
            q["bin_center"] = 0.0
            out.append(q)
            continue
        lo, hi = float(positive.min()), float(positive.max())
        edges = np.geomspace(lo, hi, n_bins + 1)
        edges = np.unique(edges)
        if len(edges) < 2:
            q["bin_center"] = 0.0
            out.append(q)
            continue
        idx = np.digitize(q.tokens_seen.to_numpy(), edges, right=False)
        q["bin_index"] = idx
        centers = {0: 0.0}
        for i in range(1, len(edges)):
            centers[i] = float(np.sqrt(edges[i - 1] * edges[i]))
        q["bin_center"] = q.bin_index.map(centers)
        q = (
            q.groupby(["architecture", "seed", "bin_index", "bin_center"], as_index=False)["preference"]
            .mean()
        )
        out.append(q)
    return pd.concat(out, ignore_index=True)


def _ticks(max_tokens: float) -> tuple[list[float], list[str]]:
    vals = [0.0, 1e5, 1e6, 1e7, 1e8, 1e9, 1e10]
    vals = [v for v in vals if v == 0 or v <= max_tokens * 1.05]
    labels = []
    for v in vals:
        if v == 0:
            labels.append("0")
        elif v >= 1e9:
            labels.append(f"{v / 1e9:.0f}B")
        elif v >= 1e6:
            labels.append(f"{v / 1e6:.0f}M")
        else:
            labels.append(f"{v / 1e3:.0f}K")
    return list(np.log10(np.asarray(vals) + 1)), labels


def _plot_stage(d: pd.DataFrame, key: str, out: Path) -> None:
    stage_value, stage_label = STAGES[key]
    d = d[d.stage_segment.eq(stage_value)].copy()
    binned = _bin_seed_trajectories(d)
    if binned.empty:
        raise RuntimeError(f"No rows for stage {stage_value}")
    max_tokens = float(binned.bin_center.max())
    xticks, xlabels = _ticks(max_tokens)
    all_seeds = sorted(int(x) for x in binned.seed.unique())
    palette = plt.cm.tab20(np.linspace(0, 1, max(2, len(all_seeds))))
    seed_colors = dict(zip(all_seeds, palette))
    arch_colors = dict(zip(ARCHES, plt.cm.Dark2.colors[: len(ARCHES)]))

    fig, axes = plt.subplots(2, 3, figsize=(17, 10), sharex=True, sharey=True)
    axes = axes.ravel()
    fig.suptitle(
        f"{stage_label} by seed and architecture\n"
        "Thin lines = individual seeds; heavy line = mean ± 1 SE across seeds; "
        "conditions and categories are collapsed to the seed level",
        fontsize=16,
        fontweight="bold",
        y=0.99,
    )
    for ax, arch in zip(axes, ARCHES):
        q = binned[binned.architecture.eq(arch)]
        n_seeds = q.seed.nunique()
        for seed, z in q.groupby("seed", sort=True):
            x = np.log10(z.bin_center.to_numpy() + 1)
            ax.plot(x, z.preference, color=seed_colors[int(seed)], lw=0.8, alpha=0.48)
        stats = (
            q.groupby("bin_center")["preference"]
            .agg(mean="mean", sd="std", n="count")
            .reset_index()
            .sort_values("bin_center")
        )
        x = np.log10(stats.bin_center.to_numpy() + 1)
        y = stats["mean"].to_numpy()
        se = stats["sd"].fillna(0).to_numpy() / np.sqrt(stats["n"].to_numpy())
        c = arch_colors[arch]
        ax.fill_between(x, np.clip(y - se, 0, 1), np.clip(y + se, 0, 1), color=c, alpha=0.22, lw=0)
        ax.plot(x, y, color=c, lw=2.5, label=f"mean ± 1 SE; n={n_seeds} seeds")
        ax.set_title(f"{arch} (n={n_seeds} seeds)", loc="left", fontweight="bold")
        ax.set_ylim(-0.02, 1.02)
        ax.axhline(0.5, color="0.55", ls=":", lw=1)
        ax.grid(True, alpha=0.25)
        ax.set_ylabel("P(overt preferred)")
        ax.set_xticks(xticks, xlabels)
        ax.set_xlim(-0.1, np.log10(max_tokens + 1) + 0.03)
    for ax in axes[-3:]:
        ax.set_xlabel("Tokens seen (log scale; log1p display keeps 0 visible)")

    # One compact global seed key keeps the individual lines identifiable
    # without repeating a large legend in every architecture panel.
    handles = [plt.Line2D([0], [0], color=seed_colors[s], lw=1.5, label=f"s{s}") for s in all_seeds]
    fig.legend(handles=handles, loc="lower center", ncol=min(7, len(handles)), frameon=False,
               bbox_to_anchor=(0.5, -0.015), fontsize=8, title="Seed")
    fig.tight_layout(rect=(0, 0.08, 1, 0.95))
    fig.savefig(out, dpi=180, bbox_inches="tight")
    plt.close(fig)

    # Save the exact seed/bin values used for this figure for auditability.
    binned.to_csv(out.with_suffix(".csv"), index=False)


def main() -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    d = pd.read_csv(INPUT)
    d["architecture"] = d["architecture"].astype(str)
    d["stage_segment"] = d["stage_segment"].astype(str)
    d["seed"] = d["seed"].astype(int)
    d["tokens_seen"] = d["tokens_seen"].astype(float)
    filenames = {
        "early": "early_starts_by_seed.png",
        "late": "late_continuations_by_seed.png",
    }
    for key, filename in filenames.items():
        _plot_stage(d, key, FIG_DIR / filename)
    readme = FIG_DIR / "README.md"
    text = readme.read_text() if readme.exists() else "# Foundry trajectory figures\n"
    addition = (
        "\n## Seed-resolved overview\n\n"
        "- `early_starts_by_seed.png`: all early-only starts, one thin line per seed and one panel per architecture.\n"
        "- `late_continuations_by_seed.png`: all late continuation segments, one thin line per seed and one panel per architecture.\n\n"
        "These overview plots first average equally across conditions and categories within each seed, then compute the heavy mean and ±1 standard error across seeds. The SE is therefore uncertainty of the seed mean, not item-level uncertainty; the earlier broad ribbons were SD across heterogeneous cells.\n"
    )
    if "## Seed-resolved overview" not in text:
        readme.write_text(text.rstrip() + "\n" + addition)
    print(f"Wrote seed-resolved figures to {FIG_DIR}")


if __name__ == "__main__":
    main()
