FIXTURES = Path(__file__).parent / "fixtures"
EXPECTED_PARQUET = FIXTURES / "golden_expected.parquet"
MODEL_STATE = FIXTURES / "golden_model_state.pt"
STIMULI_CSV = FIXTURES / "golden_stimuli.csv"


