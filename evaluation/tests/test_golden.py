"""D13 test: golden regression (CI GATE).

Pinned fixtures:
- A tiny randomly-initialized GPT-2 with fixed seed (state_dict saved to
  `fixtures/golden_model_state.pt`).
- A fixed set of v2 stimuli (embedded in this file).
- Expected per-item MeanLP / SLOR / hotspot values (baked into
  `fixtures/golden_expected.parquet`).

On every CI run: load the fixtures, run the full evaluator pipeline,
assert that the item-level output matches the expected parquet to
`atol=1e-5`. Any code change that silently shifts numerics — tokenizer
behavior, batching, SLOR formula, hotspot resolution — fails this test.

The expected fixture is generated by `_generate_golden()` below on
first-ever run (when no parquet exists). Delete the parquet + state dict
to force regeneration after an intentional change; commit the refreshed
files alongside that change.
"""

