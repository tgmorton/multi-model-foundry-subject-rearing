GOLDEN_VOCAB_SIZE = 128
GOLDEN_SEED = 12345

# Columns in the expected parquet (kept narrow to avoid brittleness on
# fields like `checkpoint_path` that are path-dependent).
_COMPARE_COLUMNS = [
    "item_id", "category", "condition", "pronoun_status", "language",
    "target_sum_log_prob", "target_mean_log_prob", "target_n_tokens",
    "target_unigram_sum_log_prob", "slor", "hotspot_log_prob",
]


# --- Helpers ----------------------------------------------------------------

def _build_stimuli_csv():
    FIXTURES.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(_STIMULI_ROWS)
    df.to_csv(STIMULI_CSV, index=False)


def _make_tiny_gpt2():
    from transformers import GPT2Config, GPT2LMHeadModel
    torch.manual_seed(GOLDEN_SEED)
    cfg = GPT2Config(
        vocab_size=GOLDEN_VOCAB_SIZE, n_positions=64, n_embd=32,
        n_layer=2, n_head=2, use_cache=True,
    )
    return GPT2LMHeadModel(cfg)


def _word_tokenizer():
    """Fixed, deterministic word→id mapping for reproducibility."""
    fixed_map = {
        "ana": 10, "won": 11, "prize": 12, "she": 13, "shows": 14,
        "pride": 15, ".": 16, "where": 17, "is": 18, "vase": 19,
        "?": 20, "put": 21, "it": 22, "on": 23, "table": 24,
    }

    def encode(text):
        return [fixed_map[w] for w in text.split()]

    tok = MagicMock()
    tok.bos_id.return_value = 1
    tok.eos_id.return_value = -1
    tok.pad_id.return_value = 0
    tok.get_piece_size.return_value = GOLDEN_VOCAB_SIZE
    tok.encode.side_effect = encode
    rev = {v: k for k, v in fixed_map.items()}
    tok.decode.side_effect = lambda ids: " ".join(rev.get(i, f"<{i}>") for i in ids)
    return tok


def _write_model_state(state_path: Path):
    state_path.parent.mkdir(parents=True, exist_ok=True)
    m = _make_tiny_gpt2()
    torch.save(m.state_dict(), state_path)


def _load_model():
    if not MODEL_STATE.exists():
        _write_model_state(MODEL_STATE)
    m = _make_tiny_gpt2()  # architecture only
    m.load_state_dict(torch.load(MODEL_STATE, map_location="cpu"))
    m.eval()
    return m


def _run_pipeline(tmp_path: Path):
    """Run the full evaluator pipeline on the golden inputs.
    Returns the per-item DataFrame restricted to _COMPARE_COLUMNS.
    """
    _build_stimuli_csv()
    tok = _word_tokenizer()
    # Use the state file bytes as the "tokenizer file" for hashing purposes —
    # arbitrary but stable.
    tok_file = FIXTURES / "golden_tok.bin"
    if not tok_file.exists():
        tok_file.write_bytes(b"golden-tok-bytes-0001")
    cache = build_cache([STIMULI_CSV], tok, tok_file)

    # Uniform unigram with fixed counts so SLOR is deterministic
    unigram = UnigramTable(
        counts=np.ones(GOLDEN_VOCAB_SIZE, dtype=np.int64),
        vocab_size=GOLDEN_VOCAB_SIZE, total_tokens=GOLDEN_VOCAB_SIZE,
        smoothing_alpha=1.0, corpus_id="golden", tokenizer_id=cache.tokenizer_id,
    )

    # Write the model state to a fake checkpoint dir
    ckpt_root = tmp_path / "model"
    ckpt_dir = ckpt_root / "checkpoint-1"
    ckpt_dir.mkdir(parents=True)
    if not MODEL_STATE.exists():
        _write_model_state(MODEL_STATE)
    (ckpt_dir / "pytorch_model.bin").write_bytes(MODEL_STATE.read_bytes())

    cell = CellSpec(
        cell_id="golden",
        architecture="gpt2",
        intervention="baseline",
        rep=0,
        checkpoint_root=ckpt_root,
        model_factory=_make_tiny_gpt2,
        stimuli=cache,
        unigram=unigram,
        device="cpu",
        batch_size=4,
    )
    runner = PerModelRunner(cell)
    items, _ = runner.run()

    df = pd.DataFrame([{c: getattr(r, c) for c in _COMPARE_COLUMNS}
                        for r in items])
    df = df.sort_values(["item_id", "pronoun_status"]).reset_index(drop=True)
    return df


def _generate_golden():
    """Regenerate the expected fixture from the current code. Run this
    intentionally after an accepted code change: delete the parquet,
    run the test once to regenerate, commit the new fixture.
    """
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        df = _run_pipeline(Path(td))
    FIXTURES.mkdir(parents=True, exist_ok=True)
    df.to_parquet(EXPECTED_PARQUET, index=False)
    return df


# --- The gate ---------------------------------------------------------------

def test_golden_item_level(tmp_path):
    """Run the evaluator on golden inputs; compare to expected parquet."""
    if not EXPECTED_PARQUET.exists():
        pytest.skip(
            "Golden expected parquet not present — regenerate with "
            "`_generate_golden()` and commit the file."
        )
    expected = pd.read_parquet(EXPECTED_PARQUET)
    actual = _run_pipeline(tmp_path)

    # Categorical columns must match exactly
    for col in ("item_id", "category", "condition", "pronoun_status", "language",
                "target_n_tokens"):
        assert list(actual[col]) == list(expected[col]), (
            f"mismatch in categorical column {col}"
        )

    # Numeric columns: tight tolerance
    for col in ("target_sum_log_prob", "target_mean_log_prob",
                "target_unigram_sum_log_prob", "slor", "hotspot_log_prob"):
        diffs = np.abs(actual[col].to_numpy() - expected[col].to_numpy())
        max_diff = float(diffs.max())
        assert max_diff <= 1e-5, f"{col}: max|Δ|={max_diff} > 1e-5"


def test_golden_fixture_writeable_via_helper(tmp_path):
    """Sanity: `_generate_golden` produces a non-empty parquet.

    Runs only in an isolated tmp FIXTURES directory so we don't touch
    the committed golden artifact.
    """
    global EXPECTED_PARQUET, MODEL_STATE, STIMULI_CSV, FIXTURES
    orig = (FIXTURES, EXPECTED_PARQUET, MODEL_STATE, STIMULI_CSV)
    try:
        FIXTURES = tmp_path / "fx"  # type: ignore[assignment]
        EXPECTED_PARQUET = FIXTURES / "golden_expected.parquet"  # type: ignore[assignment]
        MODEL_STATE = FIXTURES / "golden_model_state.pt"  # type: ignore[assignment]
        STIMULI_CSV = FIXTURES / "golden_stimuli.csv"  # type: ignore[assignment]
        df = _generate_golden()
        assert EXPECTED_PARQUET.exists()
        assert len(df) == len(_STIMULI_ROWS)
    finally:
        # Restore
        FIXTURES, EXPECTED_PARQUET, MODEL_STATE, STIMULI_CSV = orig  # type: ignore[assignment]
